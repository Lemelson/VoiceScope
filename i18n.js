  function matchLanguageTag(tag) {
    const base = String(tag || "").toLowerCase().split(/[-_]/)[0];
    return LANGUAGES.some((language) => language.code === base) ? base : null;
  }

  function normalizeLanguageTag(tag) {
    return matchLanguageTag(tag) || "en";
  }

  function preferredLanguage(tags) {
    for (const tag of tags || []) {
      const code = matchLanguageTag(tag);
      if (code) return code;
    }
    return "en";
  }

  function orderedLanguages(systemTag) {
    const preferred = normalizeLanguageTag(systemTag);
    const english = LANGUAGES.find((language) => language.code === "en");
    const system = LANGUAGES.find((language) => language.code === preferred);
    return [
      english,
      ...(system && system.code !== "en" ? [system] : []),
      ...LANGUAGES.filter((language) =>
        language.code !== "en" && language.code !== preferred
      ),
    ];
  }

  function translate(language, key, variables) {
    const bundle = STRINGS[normalizeLanguageTag(language)] || STRINGS.en;
    let value = bundle[key] ?? STRINGS.en[key] ?? key;
    for (const [name, replacement] of Object.entries(variables || {})) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  }

  return {
    LANGUAGES,
    STRINGS,
    matchLanguageTag,
    normalizeLanguageTag,
    preferredLanguage,
    orderedLanguages,
    translate,
  };
